/**
 * Self-hosts the brand fonts at STABLE URLs so the critical ones can be preloaded from index.html
 * (Fontsource's own CSS produces hashed URLs, which cannot be preloaded).
 *   node scripts/build-fonts.mjs        (npm run fonts — rerun after upgrading a @fontsource package)
 *
 * Keeps only the latin + latin-ext subsets and woff2 files. Writes:
 *   public/fonts/*.woff2      the font files
 *   src/styles/fonts.css      @font-face rules (imported by src/styles/fonts.ts)
 */
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const SOURCES = [
  '@fontsource/instrument-serif/400.css',
  '@fontsource/instrument-serif/400-italic.css',
  '@fontsource-variable/space-grotesk/wght.css',
  '@fontsource-variable/dm-sans/wght.css',
  '@fontsource-variable/dm-sans/wght-italic.css',
  '@fontsource/dm-mono/400.css',
  '@fontsource/dm-mono/500.css',
]
const KEEP_SUBSETS = ['latin', 'latin-ext']

const outDir = path.join(ROOT, 'public/fonts')
await mkdir(outDir, { recursive: true })

const rules = []
for (const source of SOURCES) {
  const cssPath = path.join(ROOT, 'node_modules', source)
  const css = await readFile(cssPath, 'utf8')
  const blocks = css.split('/*').slice(1).map((chunk) => '/*' + chunk)
  for (const block of blocks) {
    const subset = block.match(/^\/\*\s*([\w-]+)\s*\*\//)?.[1] ?? ''
    // Fontsource names blocks like "instrument-serif-latin-400-normal" — match the subset segment.
    if (!KEEP_SUBSETS.some((keep) => new RegExp(`-${keep}-(\\d|wght)`).test(subset))) continue
    const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1]
    if (!woff2) continue
    await copyFile(path.join(path.dirname(cssPath), 'files', woff2), path.join(outDir, woff2))
    const rule = block
      .replace(/src:[^;]+;/, `src: url(/fonts/${woff2}) format('woff2');`)
      .trim()
    rules.push(rule)
  }
}

const banner = `/* Generated by scripts/build-fonts.mjs — do not edit by hand. Run \`npm run fonts\`. */\n`
await writeFile(path.join(ROOT, 'src/styles/fonts.css'), banner + rules.join('\n\n') + '\n')
console.log(`Wrote ${rules.length} @font-face rules and copied files to public/fonts/`)
